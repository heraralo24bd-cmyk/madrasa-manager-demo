  /* পুরো পেজ অনুবাদ — টেক্সট, placeholder, title */
  apply(lang) {
    this.lang = (lang === 'en') ? 'en' : 'bn';
    const en = this.lang === 'en';
    const root = document.body;

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((n) => {
      const raw = n.nodeValue;
      const key = raw.trim();
      if (!key) return;
      if (!n.parentElement || n.parentElement.closest('script,style,[translate="no"]')) return;
      const el = n.parentElement;
      if (!el.dataset.i18nBn) {
        if (this.dict[key] === undefined && !Object.values(this.dict).includes(key)) return;
      }
      if (n.__bn === undefined || (raw !== n.__bn && raw.trim() !== this.dict[n.__bn.trim()])) {
        const original = Object.keys(this.dict).find(k => this.dict[k] === key);
        n.__bn = original ? raw.replace(key, original) : raw;
      }
      if (en) {
        const tr = this.dict[n.__bn.trim()];
        if (tr) n.nodeValue = raw.replace(key, tr);
      } else {
        n.nodeValue = n.__bn;
      }
    });

    document.querySelectorAll('input[placeholder],textarea[placeholder]').forEach((el) => {
      if (!el.dataset.phBn) el.dataset.phBn = el.getAttribute('placeholder');
      const tr = this.ph[el.dataset.phBn];
      el.setAttribute('placeholder', en && tr ? tr : el.dataset.phBn);
    });

    document.querySelectorAll('[title]').forEach((el) => {
      if (!el.dataset.titleBn) el.dataset.titleBn = el.getAttribute('title');
      const tr = this.dict[el.dataset.titleBn];
      el.setAttribute('title', en && tr ? tr : el.dataset.titleBn);
    });
  }
