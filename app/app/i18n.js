(function () {
  if (typeof languageText === 'object') {
    MM.i18n.dict = Object.assign({}, languageText, MM.i18n.dict);
  }
  if (typeof window.languageText === 'object') Object.assign(window.languageText, MM.i18n.dict);
  const orig = window.setLanguage;
  window.setLanguage = function (lang) {
    const l = lang === 'en' ? 'en' : 'bn';
    try { if (typeof orig === 'function') orig(l); } catch (e) {}
    MM.i18n.apply(l);
    MM.settings?.applyProfile();
    MM.router?.refreshNav();
  };
  document.addEventListener('DOMContentLoaded', function () {
    let l = 'bn';
    try { l = localStorage.getItem('mm-language') || 'bn'; } catch (e) {}
    MM.i18n.lang = l;
  });
})();
